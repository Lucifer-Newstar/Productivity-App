#!/usr/bin/env node
const fs=require('fs'), path=require('path');
const root=path.resolve(__dirname,'..'), repo=path.resolve(root,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
let pass=0,fail=0;
function test(label,ok){if(ok){pass++;console.log(`  ✓ ${label}`)}else{fail++;console.error(`  ✗ ${label}`)}}
const types=read('lib/entertainmentTypes.ts'), store=read('lib/store.tsx'), page=read('components/entertainment/EntertainmentPage.tsx'), route=read('pages/entertainment/index.tsx');
console.log('\n── Entertainment Wave 0/1 ──');
test('six media types',/"book" \| "comic" \| "manga" \| "movie" \| "series" \| "anime"/.test(types));
test('five tracking statuses',/"planned" \| "in-progress" \| "completed" \| "paused" \| "dropped"/.test(types));
test('type-aware page progress',types.includes('currentPage')&&types.includes('totalPages'));
test('type-aware chapter/volume progress',types.includes('currentChapter')&&types.includes('totalVolumes'));
test('type-aware episode/season progress',types.includes('currentEpisode')&&types.includes('totalSeasons'));
test('rating, review and notes fields',types.includes('rating?:')&&types.includes('review?:')&&types.includes('notes?:'));
test('dates and repeats fields',types.includes('startedAt?:')&&types.includes('completedAt?:')&&types.includes('repeats:'));
test('priority, queue and tags fields',types.includes('priority:')&&types.includes('queueOrder:')&&types.includes('tags:'));
test('favorites and archive fields',types.includes('favorite:')&&types.includes('archived:'));
test('schema version is explicit',types.includes('schemaVersion: 1'));
test('defensive migration exists',types.includes('migrateEntertainment'));
test('first-run seed covers all sections',Array.from(types.matchAll(/type:"(book|comic|manga|movie|series|anime)"/g)).length>=5);
test('store persists dedicated key',store.includes('"kaizen.entertainment"'));
test('store exposes functional updater',store.includes('updateEntertainment'));
